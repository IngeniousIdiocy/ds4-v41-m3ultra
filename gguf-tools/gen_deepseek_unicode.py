#!/usr/bin/env python3
"""Regenerate ds4_deepseek_unicode.inc, the codepoint classes of the DeepSeek
V4 / V4.1 pre-tokenizer regex (\\p{L} \\p{M} \\p{N} \\p{P} \\p{S} \\s), as the
Hugging Face `tokenizers` library matches them. Each class is probed through
a Split pre-tokenizer, so the tables follow its regex engine's Unicode data.

Usage: python gen_deepseek_unicode.py > ../ds4_deepseek_unicode.inc
"""
import sys

import tokenizers
from tokenizers import Regex
from tokenizers.pre_tokenizers import Split

CLASSES = [("L", r"\p{L}"), ("M", r"\p{M}"), ("N", r"\p{N}"),
           ("P", r"\p{P}"), ("S", r"\p{S}"), ("WS", r"\s")]
CHUNK = 4096


def members(pattern):
    """Codepoints the pattern matches: those a Removed split drops."""
    split = Split(Regex(pattern), behavior="removed")
    found = set()
    cps = [cp for cp in range(0x110000) if not 0xD800 <= cp <= 0xDFFF]
    for i in range(0, len(cps), CHUNK):
        chunk = cps[i:i + CHUNK]
        kept = [False] * len(chunk)
        for _, (a, b) in split.pre_tokenize_str("".join(map(chr, chunk))):
            for k in range(a, b):
                kept[k] = True
        found.update(cp for cp, k in zip(chunk, kept) if not k)
    return found


def main() -> None:
    sets = [(name, members(pattern)) for name, pattern in CLASSES]
    ranges = []
    lo = prev = mask = None
    for cp in range(0x110000):
        m = sum(1 << i for i, (_, s) in enumerate(sets) if cp in s)
        if m and lo is not None and m == mask and cp == prev + 1:
            prev = cp
            continue
        if lo is not None:
            ranges.append((lo, prev, mask))
            lo = None
        if m:
            lo, prev, mask = cp, cp, m
    if lo is not None:
        ranges.append((lo, prev, mask))
    out = sys.stdout
    out.write("/* Generated by gguf-tools/gen_deepseek_unicode.py from the Hugging Face\n")
    out.write(f" * tokenizers {tokenizers.__version__} regex engine: codepoint classes of the\n")
    out.write(" * DeepSeek pre-tokenizer, one class mask per range. */\n\n")
    for i, (name, _) in enumerate(sets):
        out.write(f"#define DS4_UCLASS_{name} {1 << i}u\n")
    out.write("\ntypedef struct { uint32_t lo, hi, mask; } ds4_deepseek_urange;\n\n")
    out.write("static const ds4_deepseek_urange ds4_deepseek_uranges[] = {\n")
    for i in range(0, len(ranges), 3):
        out.write("    " + " ".join(f"{{0x{a:05x}, 0x{b:05x}, {m}}}," for a, b, m in ranges[i:i + 3]) + "\n")
    out.write("};\n")


if __name__ == "__main__":
    main()
